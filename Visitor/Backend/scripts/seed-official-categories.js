async function seed() {
  console.log('Starting seed of official visitor categories...');

  // Soft delete all random test categories
  await pool.query(
    "UPDATE visitor_categories SET is_deleted = TRUE, deleted_at = NOW() WHERE category_name LIKE 'Visitor Category %' OR category_name LIKE 'VIP Guest %' OR (category_name = 'VIP' AND category_code = 'VIP-21')"
  );

  for (const cat of officialCategories) {
    const existing = await pool.query("SELECT id FROM visitor_categories WHERE category_name = ?", [cat.category_name]);
    let catId;
    if (existing && existing.length > 0) {
      catId = existing[0].id;
      await pool.query(
        `UPDATE visitor_categories SET
          category_code = ?,
          description = ?,
          default_visit_duration = ?,
          default_duration_minutes = ?,
          max_visit_duration = ?,
          max_duration_minutes = ?,
          access_level = ?,
          status = 'Active',
          display_order = ?,
          approval_required = ?,
          allow_walkin_visitor = ?,
          allow_repeat_visit = ?,
          appointment_required = ?,
          host_approval_required = ?,
          department_approval_required = ?,
          security_approval_required = ?,
          visitor_pass_required = ?,
          identity_verification_required = ?,
          face_verification_required = ?,
          document_verification_required = ?,
          escort_required = ?,
          vehicle_registration_required = ?,
          emergency_contact_required = ?,
          is_archived = FALSE,
          is_deleted = FALSE,
          deleted_at = NULL
        WHERE id = ?`,
        [
          cat.category_code, cat.description, cat.default_visit_duration, cat.default_duration_minutes,
          cat.max_visit_duration, cat.max_duration_minutes, cat.access_level, cat.display_order,
          cat.approval_required, cat.allow_walkin_visitor, cat.allow_repeat_visit, cat.appointment_required,
          cat.host_approval_required, cat.department_approval_required, cat.security_approval_required,
          cat.visitor_pass_required, cat.identity_verification_required, cat.face_verification_required,
          cat.document_verification_required, cat.escort_required, cat.vehicle_registration_required,
          cat.emergency_contact_required, catId
        ]
      );
    } else {
      const insertRes = await pool.query(
        `INSERT INTO visitor_categories (
          category_name, category_code, description, default_visit_duration, default_duration_minutes,
          max_visit_duration, max_duration_minutes, access_level, status, display_order,
          approval_required, allow_walkin_visitor, allow_repeat_visit, appointment_required,
          host_approval_required, department_approval_required, security_approval_required,
          visitor_pass_required, identity_verification_required, face_verification_required,
          document_verification_required, escort_required, vehicle_registration_required,
          emergency_contact_required, is_archived, is_deleted
        ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, 'Active', ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, FALSE, FALSE)`,
        [
          cat.category_name, cat.category_code, cat.description, cat.default_visit_duration, cat.default_duration_minutes,
          cat.max_visit_duration, cat.max_duration_minutes, cat.access_level, cat.display_order,
          cat.approval_required, cat.allow_walkin_visitor, cat.allow_repeat_visit, cat.appointment_required,
          cat.host_approval_required, cat.department_approval_required, cat.security_approval_required,
          cat.visitor_pass_required, cat.identity_verification_required, cat.face_verification_required,
          cat.document_verification_required, cat.escort_required, cat.vehicle_registration_required,
          cat.emergency_contact_required
        ]
      );
      catId = insertRes.insertId;
    }

    // Insert access levels
    await pool.query("DELETE FROM visitor_category_access_levels WHERE category_id = ?", [catId]);
    for (const area of cat.areas) {
      await pool.query("INSERT INTO visitor_category_access_levels (category_id, location_name, is_granted) VALUES (?, ?, TRUE)", [catId, area]);
    }
  }

  const result = await pool.query("SELECT id, category_name, category_code, access_level, status, display_order FROM visitor_categories WHERE is_deleted = FALSE ORDER BY display_order ASC");
  console.log("Successfully seeded official visitor categories into MySQL:");
  console.table(result);
  process.exit(0);
}

seed().catch(err => {
  console.error("Seed error:", err);
  process.exit(1);
});
