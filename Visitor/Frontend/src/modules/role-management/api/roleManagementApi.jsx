import api from '../../../services/api';
export const roleManagementApi = {
    getStatistics: () => api.get('/roles/statistics'),
    listRoles: (params) => api.get('/roles', { params }),
    getRole: (id) => api.get(`/roles/${id}`),
    createRole: (data) => api.post('/roles', data),
    updateRole: (id, data) => api.put(`/roles/${id}`, data),
    activateRole: (id) => api.post(`/roles/${id}/activate`),
    deactivateRole: (id) => api.post(`/roles/${id}/deactivate`),
    archiveRole: (id) => api.post(`/roles/${id}/archive`),
    deleteRole: (id) => api.delete(`/roles/${id}`),
    restoreRole: (id) => api.post(`/roles/${id}/restore`),
    cloneRole: (id, data) => api.post(`/roles/${id}/clone`, data),
    getPermissions: (roleId) => api.get(`/roles/${roleId}/permissions`),
    syncPermissions: (roleId, permissionIds) => api.put(`/roles/${roleId}/permissions`, { permissionIds }),
    listAllPermissions: (params) => api.get('/roles/permissions/all', { params }),
    getPermissionModules: () => api.get('/roles/permissions/modules'),
    getRoleUsers: (roleId, params) => api.get(`/roles/${roleId}/users`, { params }),
    assignUser: (roleId, data) => api.post(`/roles/${roleId}/users`, data),
    removeUser: (roleId, userId) => api.delete(`/roles/${roleId}/users/${userId}`),
    getHierarchy: () => api.get('/roles/hierarchy'),
    addHierarchyLink: (data) => api.post('/roles/hierarchy', data),
    removeHierarchyLink: (id) => api.delete(`/roles/hierarchy/${id}`),
    listConflicts: () => api.get('/roles/conflicts'),
    createConflict: (data) => api.post('/roles/conflicts', data),
    deleteConflict: (id) => api.delete(`/roles/conflicts/${id}`),
    listSodRules: () => api.get('/roles/sod-rules'),
    createSodRule: (data) => api.post('/roles/sod-rules', data),
    deleteSodRule: (id) => api.delete(`/roles/sod-rules/${id}`),
    listTemplates: () => api.get('/roles/templates'),
    instantiateTemplate: (data) => api.post('/roles/templates/instantiate', data),
    getMatrix: () => api.get('/roles/matrix'),
    compareRoles: (role1, role2) => api.get(`/roles/compare?role1=${role1}&role2=${role2}`),
    bulkOperations: (data) => api.post('/roles/bulk-operations', data),
    exportRoles: () => api.get('/roles/export'),
};
