const LanguageContext = createContext(undefined);
export function LanguageProvider({ children }) {
    const [language, setLanguageState] = useState(() => {
        const stored = localStorage.getItem(STORAGE_KEY);
        if (stored === 'en' || stored === 'am')
            return stored;
        return 'en';
    });
    useEffect(() => {
        localStorage.setItem(STORAGE_KEY, language);
        // Set dir attribute for RTL/LTR (Amharic is LTR)
        document.documentElement.lang = language === 'am' ? 'am' : 'en';
    }, [language]);
    const toggleLanguage = useCallback(() => {
        setLanguageState((prev) => (prev === 'en' ? 'am' : 'en'));
    }, []);
    const setLanguage = useCallback((lang) => {
        setLanguageState(lang);
    }, []);
    const t = useCallback((key, fallback) => {
        return translations[language][key] || translations['en'][key] || fallback || key;
    }, [language]);
    const tStatus = useCallback((status) => {
        if (!status)
            return '';
        const norm = String(status).toLowerCase().replace(/[\s_-]+/g, '');
        const map = {
            pending: 'status.pending',
            requested: 'status.requested',
            pendingapproval: 'status.pending',
            approved: 'status.approved',
            rejected: 'status.rejected',
            checkedin: 'status.checkedIn',
            onsite: 'status.checkedIn',
            inpremise: 'status.checkedIn',
            checkedout: 'status.checkedOut',
            completed: 'status.completed',
            cancelled: 'status.cancelled',
            canceled: 'status.cancelled',
            active: 'status.active',
            inactive: 'status.inactive',
            expired: 'status.expired',
            blocked: 'status.blocked',
            blacklisted: 'status.blocked',
            overstay: 'status.overstay',
        };
        const key = map[norm] || `status.${norm}`;
        return translations[language][key] || translations['en'][key] || status;
    }, [language]);
    return (<LanguageContext.Provider value={{ language, toggleLanguage, setLanguage, t, tStatus }}>
      {children}
    </LanguageContext.Provider>);
}
export function useLanguage() {
    const context = useContext(LanguageContext);
    if (!context) {
        throw new Error('useLanguage must be used within a LanguageProvider');
    }
    return context;
}
export default LanguageContext;
